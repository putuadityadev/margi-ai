interface PlaceInput {
  /** Three hex digits appended to the shared id prefix (new places use a00 upwards). */
  readonly suffix: string;
  readonly slug: string;
  readonly kind: VenueKind;
  readonly category: VenueCategory;
  readonly nameEn: string;
  readonly nameId: string;
  readonly descriptionEn: string;
  readonly descriptionId: string;
  readonly regencyId: string;
  readonly lat: number;
  readonly lng: number;
  readonly priceLevel: number;
  readonly hotspot?: boolean;
  readonly buffer?: boolean;
  readonly hours: OpeningHours;
  readonly queue: number;
  readonly dwell: number;
  readonly etiquette: readonly EtiquetteTag[];
  readonly vibes: readonly VibeTag[];
  readonly crowd: CrowdProfile;
}

const ID_PREFIX = '0192e2b0-8c20-7193-8db6-8d5ec4f0f';

/** Same opening window on all seven days (keys '0' Monday to '6' Sunday). */
function daily(open: string, close: string): OpeningHours {
  const hours: OpeningHours = {};
  for (let day = 0; day < 7; day += 1) {
    hours[String(day)] = [[open, close]];
  }
  return hours;
}

const ALWAYS_OPEN = daily('00:00', '23:59');
const TEMPLE_HOURS = daily('08:00', '18:00');

function crowd(peakHour: number, peakBusyness: number, baseBusyness: number): CrowdProfile {
  return { peakHour, peakBusyness, baseBusyness };
}

function categoryImage(category: VenueCategory): string {
  return `/places/${category.toLowerCase().replaceAll('_', '-')}.svg`;
}

function place(input: PlaceInput): ExplorePlaceSeed {
  const venue = createVenue({
    id: `${ID_PREFIX}${input.suffix}`,
    slug: input.slug,
    kind: input.kind,
    category: input.category,
    nameEn: input.nameEn,
    nameId: input.nameId,
    descriptionEn: input.descriptionEn,
    descriptionId: input.descriptionId,
    regencyId: input.regencyId,
    lat: input.lat,
    lng: input.lng,
    imageUrl: categoryImage(input.category),
    priceLevel: input.priceLevel,
    isHotspot: input.hotspot ?? false,
    isBufferZone: input.buffer ?? false,
    openingHours: input.hours,
    typicalPeakQueueMinutes: input.queue,
    avgDwellMinutes: input.dwell,
    etiquetteTags: [...input.etiquette],
  });
  return { venue, vibeTags: input.vibes, crowd: input.crowd };
}

/** Re-uses one of the original 23 curated venues, failing loudly if the slug drifts. */
function fromExisting(
  slug: string,
  vibeTags: readonly VibeTag[],
  crowdProfile: CrowdProfile,
): ExplorePlaceSeed {
  const venue = MOCK_VENUES.find((v) => v.slug === slug);
  if (!venue) {
    throw new Error(`Unknown mock venue slug: ${slug}`);
  }
  return { venue, vibeTags, crowd: crowdProfile };
}

